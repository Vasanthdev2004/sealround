//! The canonical bid plaintext and the sealed bid's length, pinned in
//! `fixtures/canonical_bids.json` for the app (`canonicalBid`) and the relayer
//! to test against.
//!
//! The first test fails when the fixture no longer matches what this crate
//! writes. After a deliberate format change, regenerate it with
//!
//! ```text
//! FAIRGROUND_WRITE_FIXTURES=1 cargo test -p fairground-sealer --test canonical
//! ```

use std::path::PathBuf;

use base64::Engine as _;
use base64::engine::general_purpose::STANDARD as BASE64;
use fairground_clearing::hash::{SALT_LEN, parse_hex, to_hex};
use fairground_clearing::{
    BID_PLAINTEXT_FIXED_LEN, PADDED_AMOUNT_DIGITS, SEALED_BOX_OVERHEAD, bid_plaintext_len,
    sealed_bid_len,
};
use fairground_sealer::{BidPlaintext, SaleKeypair, open_bid, seal_bid};
use serde::Serialize;
use serde_json::Value;

const FIXTURE: &str = "tests/fixtures/canonical_bids.json";
const WRITE_VAR: &str = "FAIRGROUND_WRITE_FIXTURES";

/// Shortest and longest ids the contract accepts, and typical ones.
const SALE_MIN: &str = "a";
const SALE_TYPICAL: &str = "fairt";
const SALE_MAX: &str = "fair-sale_2026-max-length-id-032";
const BIDDER_MIN: &str = "ab";
const BIDDER_TYPICAL: &str = "alice.testnet";
const BIDDER_ETH: &str = "0x1234567890abcdef1234567890abcdef12345678";
const BIDDER_MAX: &str = "98793cd91a3f870fb126f66285808c7e094afcfc4eda8a970f6648cdf0dbd6de";

#[derive(Serialize)]
struct Fixture {
    about: &'static str,
    padded_amount_digits: usize,
    plaintext_len: &'static str,
    sealed_len: &'static str,
    sealed_base64_len: &'static str,
    rows: Vec<Row>,
}

/// One bid: its fields (amounts as plain decimal strings, salt as hex), the
/// exact canonical plaintext, and the lengths.
#[derive(Serialize)]
struct Row {
    sale_id: String,
    bidder: String,
    max_price: String,
    max_spend: String,
    salt: String,
    plaintext: String,
    plaintext_len: usize,
    sealed_len: usize,
    sealed_base64_len: usize,
}

fn base64_len(bytes: usize) -> usize {
    bytes.div_ceil(3) * 4
}

/// The bids in the fixture: every power of ten in both amounts, zero, one,
/// u128::MAX, numbers one below a power of ten, typical amounts, and the
/// shortest and longest ids in every combination.
fn cases() -> Vec<BidPlaintext> {
    let ids = [
        (SALE_TYPICAL, BIDDER_TYPICAL),
        (SALE_MIN, BIDDER_MIN),
        (SALE_MAX, BIDDER_MAX),
        (SALE_MIN, BIDDER_MAX),
        (SALE_MAX, BIDDER_MIN),
        (SALE_TYPICAL, BIDDER_ETH),
    ];
    let mut amounts: Vec<(u128, u128)> = vec![
        // 0.0016 USDC per token, 5 USDC.
        (1_600, 5_000_000),
        (1_000, 50_000_000),
        (250_000, 200_000_000),
        (0, 0),
        (1, 1),
        (u128::MAX, u128::MAX),
        (0, u128::MAX),
        (u128::MAX, 0),
        (9, 99),
        (999_999, 999_999_999_999),
        (10u128.pow(38) - 1, u128::MAX - 1),
    ];
    amounts.extend((0..=38).map(|k| (10u128.pow(k), 10u128.pow(38 - k))));
    let mut bids: Vec<BidPlaintext> = amounts
        .into_iter()
        .enumerate()
        .map(|(i, (max_price, max_spend))| {
            let (sale_id, bidder) = ids[i % ids.len()];
            BidPlaintext {
                sale_id: sale_id.into(),
                bidder: bidder.into(),
                max_price,
                max_spend,
                salt: core::array::from_fn(|j| {
                    u8::try_from((i * 31 + j * 7) % 256).expect("below 256")
                }),
            }
        })
        .collect();
    // Every id combination with the typical amounts, and the extreme salts.
    for (n, (sale_id, bidder)) in ids.into_iter().enumerate() {
        bids.push(BidPlaintext {
            sale_id: sale_id.into(),
            bidder: bidder.into(),
            max_price: 1_600,
            max_spend: 5_000_000,
            salt: [if n % 2 == 0 { 0x00 } else { 0xff }; SALT_LEN],
        });
    }
    bids
}

fn fixture() -> Fixture {
    let rows = cases()
        .into_iter()
        .map(|bid| {
            let plaintext = bid.to_canonical_json();
            let sealed_len = sealed_bid_len(bid.sale_id.len(), bid.bidder.len());
            Row {
                plaintext_len: plaintext.len(),
                sealed_len,
                sealed_base64_len: base64_len(sealed_len),
                sale_id: bid.sale_id,
                bidder: bid.bidder,
                max_price: bid.max_price.to_string(),
                max_spend: bid.max_spend.to_string(),
                salt: to_hex(&bid.salt),
                plaintext,
            }
        })
        .collect();
    Fixture {
        about: "Generated by crates/sealer/tests/canonical.rs (FAIRGROUND_WRITE_FIXTURES=1 cargo test -p fairground-sealer --test canonical); that test fails when this file is stale. \
            Each row is one bid: its fields (amounts as plain decimal strings, salt as 32 lowercase hex digits), `plaintext`, the exact canonical JSON the app seals \
            (keys sale_id, bidder, max_price, max_spend, salt in that order, no whitespace, both amounts left-padded with zeros to 39 digits), \
            and the lengths in bytes of the plaintext (UTF-8), of the sealed box (crypto_box_seal adds 48 bytes) and of the box in standard padded base64. \
            fairground_clearing::sealed_bid_len gives sealed_len; the contract refuses a TEE bid of any other decoded length.",
        padded_amount_digits: PADDED_AMOUNT_DIGITS,
        plaintext_len: "176 + len(sale_id) + len(bidder)",
        sealed_len: "plaintext_len + 48 = 224 + len(sale_id) + len(bidder)",
        sealed_base64_len: "4 * ceil(sealed_len / 3)",
        rows,
    }
}

fn fixture_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join(FIXTURE)
}

#[test]
fn the_fixture_is_up_to_date() {
    let expected = format!(
        "{}\n",
        serde_json::to_string_pretty(&fixture()).expect("plain data serializes")
    );
    let path = fixture_path();
    if std::env::var_os(WRITE_VAR).is_some() {
        std::fs::write(&path, &expected).expect("write the fixture");
        return;
    }
    let found = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("{}: {e}; generate it with {WRITE_VAR}=1", path.display()))
        .replace("\r\n", "\n");
    if found != expected {
        let line = found
            .lines()
            .zip(expected.lines())
            .position(|(a, b)| a != b)
            .map_or_else(|| "the end".to_owned(), |i| format!("line {}", i + 1));
        panic!(
            "{FIXTURE} is stale (first difference at {line}). If the format change is \
             deliberate, regenerate it with {WRITE_VAR}=1 cargo test -p fairground-sealer \
             --test canonical, and update the app and the relayer to match."
        );
    }
}

fn text<'a>(row: &'a Value, key: &str) -> &'a str {
    row[key]
        .as_str()
        .unwrap_or_else(|| panic!("{key} is a string in {row}"))
}

fn count(row: &Value, key: &str) -> usize {
    usize::try_from(
        row[key]
            .as_u64()
            .unwrap_or_else(|| panic!("{key} in {row}")),
    )
    .unwrap()
}

/// Checks every row of the file on disk against the implementation directly,
/// independently of how the file was generated.
#[test]
fn every_fixture_row_matches_the_implementation() {
    let file: Value =
        serde_json::from_str(&std::fs::read_to_string(fixture_path()).expect("read the fixture"))
            .expect("the fixture is JSON");
    assert_eq!(file["padded_amount_digits"], 39);
    let rows = file["rows"].as_array().expect("rows");
    assert!(rows.len() >= 50, "{} rows", rows.len());
    let keypair = SaleKeypair::derive(&[0x24; 32], "fairground.testnet", "fairt");
    let (mut sale_lens, mut bidder_lens) = (Vec::new(), Vec::new());

    for row in rows {
        let bid = BidPlaintext {
            sale_id: text(row, "sale_id").into(),
            bidder: text(row, "bidder").into(),
            max_price: text(row, "max_price").parse().expect("max_price is a u128"),
            max_spend: text(row, "max_spend").parse().expect("max_spend is a u128"),
            salt: parse_hex(text(row, "salt")).expect("salt is 32 hex digits"),
        };
        let plaintext = text(row, "plaintext");
        assert_eq!(bid.to_canonical_json(), plaintext);
        assert_eq!(
            BidPlaintext::from_json(plaintext.as_bytes()),
            Some(bid.clone())
        );
        for key in ["max_price", "max_spend"] {
            let padded = format!("{:0>39}", text(row, key));
            assert!(
                plaintext.contains(&format!(r#""{key}":"{padded}""#)),
                "{plaintext}"
            );
        }

        let (sale, bidder) = (bid.sale_id.len(), bid.bidder.len());
        assert_eq!(plaintext.len(), count(row, "plaintext_len"));
        assert_eq!(plaintext.len(), bid_plaintext_len(sale, bidder));
        assert_eq!(plaintext.len(), BID_PLAINTEXT_FIXED_LEN + sale + bidder);
        assert_eq!(plaintext.len(), 176 + sale + bidder);
        assert_eq!(count(row, "sealed_len"), sealed_bid_len(sale, bidder));
        assert_eq!(
            count(row, "sealed_len"),
            plaintext.len() + SEALED_BOX_OVERHEAD
        );
        assert_eq!(
            count(row, "sealed_base64_len"),
            base64_len(count(row, "sealed_len"))
        );

        // A real box has exactly that length, and opens to the same bid.
        let sealed = seal_bid(&keypair.public_key(), &bid);
        assert_eq!(sealed.len(), count(row, "sealed_base64_len"));
        assert_eq!(
            BASE64.decode(&sealed).unwrap().len(),
            count(row, "sealed_len")
        );
        assert_eq!(open_bid(&sealed, &keypair), Some(bid));

        sale_lens.push(sale);
        bidder_lens.push(bidder);
    }
    // The extremes the contract allows are covered.
    assert_eq!(sale_lens.iter().min(), Some(&1));
    assert_eq!(sale_lens.iter().max(), Some(&32));
    assert_eq!(bidder_lens.iter().min(), Some(&2));
    assert_eq!(bidder_lens.iter().max(), Some(&64));
    for amount in ["0", "1", "340282366920938463463374607431768211455"] {
        assert!(rows.iter().any(|row| row["max_price"] == amount));
        assert!(rows.iter().any(|row| row["max_spend"] == amount));
    }
    for k in 0..=38 {
        let power = 10u128.pow(k).to_string();
        assert!(rows.iter().any(|row| row["max_price"] == power.as_str()));
        assert!(rows.iter().any(|row| row["max_spend"] == power.as_str()));
    }
}

/// Every sale id length the contract allows (1 to 32 bytes) with every
/// account id length (2 to 64): a sealed bid is `sealed_bid_len` bytes,
/// whatever its amounts.
#[test]
fn seal_bid_output_is_sealed_bid_len_for_every_id_length() {
    let keypair = SaleKeypair::derive(&[0x24; 32], "fairground.testnet", "fairt");
    let public_key = keypair.public_key();
    let amounts = [
        0,
        1,
        10,
        1_600,
        5_000_000,
        10u128.pow(20),
        10u128.pow(38),
        u128::MAX,
    ];
    let mut sealed_count = 0;
    for sale_len in 1..=32 {
        for bidder_len in 2..=64 {
            let i = sale_len * 64 + bidder_len;
            let bid = BidPlaintext {
                sale_id: "s".repeat(sale_len),
                bidder: "b".repeat(bidder_len),
                max_price: amounts[i % amounts.len()],
                max_spend: amounts[(i / amounts.len()) % amounts.len()],
                salt: [u8::try_from(i % 256).unwrap(); SALT_LEN],
            };
            assert_eq!(
                bid.to_canonical_json().len(),
                bid_plaintext_len(sale_len, bidder_len)
            );
            let sealed = BASE64.decode(seal_bid(&public_key, &bid)).unwrap();
            assert_eq!(
                sealed.len(),
                sealed_bid_len(sale_len, bidder_len),
                "{sale_len} / {bidder_len}"
            );
            sealed_count += 1;
        }
    }
    assert_eq!(sealed_count, 32 * 63);
}

/// The fixture's named ids really are the extremes and are valid ids.
#[test]
fn the_named_ids_have_the_lengths_they_claim() {
    assert_eq!(SALE_MIN.len(), 1);
    assert_eq!(SALE_MAX.len(), 32);
    assert_eq!(BIDDER_MIN.len(), 2);
    assert_eq!(BIDDER_ETH.len(), 42);
    assert_eq!(BIDDER_MAX.len(), 64);
    // Nothing in them needs escaping in JSON, which the length formula assumes.
    for id in [
        SALE_MIN,
        SALE_TYPICAL,
        SALE_MAX,
        BIDDER_MIN,
        BIDDER_TYPICAL,
        BIDDER_ETH,
        BIDDER_MAX,
    ] {
        assert!(
            id.bytes()
                .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b"._-".contains(&b)),
            "{id}"
        );
        assert_eq!(serde_json::to_string(id).unwrap(), format!("\"{id}\""));
    }
}
